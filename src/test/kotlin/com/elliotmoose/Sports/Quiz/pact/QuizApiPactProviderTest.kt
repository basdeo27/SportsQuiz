package com.elliotmoose.Sports.Quiz.pact

import au.com.dius.pact.provider.junit5.HttpTestTarget
import au.com.dius.pact.provider.junit5.PactVerificationContext
import au.com.dius.pact.provider.junit5.PactVerificationInvocationContextProvider
import au.com.dius.pact.provider.junitsupport.IgnoreNoPactsToVerify
import au.com.dius.pact.provider.junitsupport.Provider
import au.com.dius.pact.provider.junitsupport.State
import au.com.dius.pact.provider.junitsupport.loader.PactFolder
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.TestTemplate
import org.junit.jupiter.api.extension.ExtendWith
import org.springframework.boot.test.context.SpringBootTest
import org.springframework.boot.test.web.server.LocalServerPort

/**
 * Provider-side Pact verification. Reads every interaction from the pact file generated by
 * QuizApiPactConsumerTest and replays each request against the real running app to confirm
 * the app's response matches the contract.
 *
 * @IgnoreNoPactsToVerify allows this test to pass when no pact files exist yet (e.g. on a clean
 * checkout before the consumer test has run). Run `./gradlew pactConsumerTest test` or simply
 * `./gradlew test` — the build wires consumer before provider automatically.
 */
@SpringBootTest(
    webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT,
    properties = [
        "quiz.questions.storage=local",
        "quiz.storage=local"
    ]
)
@Provider("sports-quiz-api")
@PactFolder("build/pacts")
@IgnoreNoPactsToVerify
@ExtendWith(PactVerificationInvocationContextProvider::class)
class QuizApiPactProviderTest {

    @LocalServerPort
    var port = 0

    @BeforeEach
    fun setUp(context: PactVerificationContext) {
        context.target = HttpTestTarget("localhost", port)
    }

    @TestTemplate
    fun verifyPact(context: PactVerificationContext) {
        context.verifyInteraction()
    }

    // --- Provider states ---
    // Each @State method corresponds to a "given(...)" clause in the consumer test.

    @State("quiz does not exist")
    fun setupQuizDoesNotExist() {
        // No action needed — the in-memory quiz store starts empty on every test run,
        // so any unknown quiz ID will always produce a 404.
    }
}
